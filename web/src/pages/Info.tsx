/** מחוברים - לטופס המשוב בפרופיל; לא מחוברים - מייל */
function Contact({ children = 'צרו קשר' }: { children?: ReactNode }) {
  const { user } = useAuth()
  return user ? <Link to={CONTACT_PATH}>{children}</Link> : <a href={`mailto:${FEEDBACK_EMAIL}`}>{children}</a>
}

