/** דפי מידע סטטיים: עזרה, שאלות נפוצות, פרטיות ותנאי שימוש. פתוחים גם בלי התחברות */
export default function InfoPage({ page }: { page: InfoPageId }) {
  const { title, body: Body } = PAGES[page]
  return (
    <article className="info-page">
      <h1>{title}</h1>
      <Card className="info-page__card">
        <Body />
      </Card>
      <nav className="info-page__more" aria-label="דפי מידע נוספים">
        {INFO_LINKS.filter((l) => l.id !== page).map((l) => (
          <Link key={l.id} to={l.path}>
            {l.label}
          </Link>
        ))}
      </nav>
    </article>
  )
}
