def _build(semesters_text: str, subjects: tuple[str, ...], has_prerequisites: bool) -> CourseInfo:
    by_year: dict[str, set[str]] = {}
    tokens = [t.strip() for t in semesters_text.split(",") if t.strip()]
    for token in tokens:
        match = _TOKEN_RE.match(token)
        if match:
            by_year.setdefault(match.group(2), set()).add(match.group(1))
    years = list(by_year.values())
    if len(years) >= 2 and all(y == years[0] for y in years):
        letters = tuple(l for l in SEMESTER_LETTERS if l in years[0])
        label = ("סמסטר " if len(letters) == 1 else "סמסטרים ") + ", ".join(letters)
        return CourseInfo(letters, True, label, has_prerequisites, subjects)
    label = f"{semesters_text} בלבד" if tokens else "לא מתוכנן ב-2027-2028"
    return CourseInfo((), False, label, has_prerequisites, subjects)


def _with_prerequisites(code: str, info: CourseInfo | None) -> CourseInfo | None:
    """משלים את הידע הקודם מדף הקורס. כשיש דף, הוא קובע אם הקורס דורש ידע קודם."""
    knowledge = PREREQUISITES.get(code)
    if knowledge is None:
        return info
    required, recommended = knowledge
    if info is None:
        # קורס שלא ברשימת המחלקה (למשל קורסי כלכלה) - יש רק ידע קודם, בלי סמסטרים ונושא
        info = CourseInfo((), False, "", False, ())
    return CourseInfo(
        info.semesters,
        info.every_year,
        info.schedule_label,
        bool(required),
        info.subjects,
        required,
        recommended,
    )


_LISTED = {code: _build(sems, subjects, pre) for code, _name, sems, subjects, pre in _RAW}
COURSE_INFO: dict[str, CourseInfo] = {
    code: info
    for code in _LISTED.keys() | PREREQUISITES.keys()
    if (info := _with_prerequisites(code, _LISTED.get(code))) is not None
}


def get_course_info(code: str | None) -> CourseInfo | None:
    if not code:
        return None
    return COURSE_INFO.get(code.strip())
